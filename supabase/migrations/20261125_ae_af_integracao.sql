-- SIA-Saúde | Integração AE -> Empenho -> AF -> Recebimentos
-- Migração inicial, aditiva e segura: não remove nem altera registros existentes.
-- Aplicar no SQL Editor do Supabase somente após revisar o ambiente.

create table if not exists public.ae_solicitacoes (
    id bigint generated by default as identity primary key,
    numero_ae text not null,
    fornecedor text not null,
    data_emissao date,
    prazo_entrega date,
    valor_total numeric(14,2) not null default 0 check (valor_total >= 0),
    status text not null default 'Aguardando empenho',
    numero_empenho text,
    data_empenho date,
    responsavel_nome text,
    observacoes text,
    origem_cadastro text not null default 'manual'
        check (origem_cadastro in ('manual', 'pdf')),
    pdf_nome text,
    pdf_storage_path text,
    usuario_id bigint references public.usuarios(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint ae_solicitacoes_numero_ae_unique unique (numero_ae)
);

create table if not exists public.ae_itens (
    id bigint generated by default as identity primary key,
    ae_id bigint not null references public.ae_solicitacoes(id) on delete cascade,
    ordem integer not null default 1,
    codigo_produto text,
    descricao text not null,
    quantidade numeric(14,3) not null default 0 check (quantidade > 0),
    unidade text not null default 'UN',
    valor_unitario numeric(14,4) not null default 0 check (valor_unitario >= 0),
    valor_total numeric(14,2) not null default 0 check (valor_total >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Vínculos opcionais: mantêm compatibilidade com os registros atuais.
alter table public.afs
    add column if not exists ae_id bigint
    references public.ae_solicitacoes(id) on delete set null;

alter table public.compras_pedidos
    add column if not exists ae_id bigint
    references public.ae_solicitacoes(id) on delete set null;

alter table public.compras_pedidos
    add column if not exists ae_item_id bigint
    references public.ae_itens(id) on delete set null;

create index if not exists idx_ae_solicitacoes_status
    on public.ae_solicitacoes(status);
create index if not exists idx_ae_solicitacoes_numero_empenho
    on public.ae_solicitacoes(numero_empenho);
create index if not exists idx_ae_itens_ae_id
    on public.ae_itens(ae_id);
create index if not exists idx_afs_ae_id
    on public.afs(ae_id);
create index if not exists idx_compras_pedidos_ae_id
    on public.compras_pedidos(ae_id);
create index if not exists idx_compras_pedidos_ae_item_id
    on public.compras_pedidos(ae_item_id);

-- Atualiza updated_at sem depender de lógica no navegador.
create or replace function public.sia_atualizar_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists trg_ae_solicitacoes_updated_at on public.ae_solicitacoes;
create trigger trg_ae_solicitacoes_updated_at
before update on public.ae_solicitacoes
for each row execute function public.sia_atualizar_updated_at();

drop trigger if exists trg_ae_itens_updated_at on public.ae_itens;
create trigger trg_ae_itens_updated_at
before update on public.ae_itens
for each row execute function public.sia_atualizar_updated_at();

-- Acesso para usuários autenticados do portal. As tabelas antigas permanecem intactas.
alter table public.ae_solicitacoes enable row level security;
alter table public.ae_itens enable row level security;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'ae_solicitacoes'
          and policyname = 'ae_solicitacoes_authenticated_all'
    ) then
        create policy ae_solicitacoes_authenticated_all
        on public.ae_solicitacoes
        for all to authenticated
        using (true) with check (true);
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'ae_itens'
          and policyname = 'ae_itens_authenticated_all'
    ) then
        create policy ae_itens_authenticated_all
        on public.ae_itens
        for all to authenticated
        using (true) with check (true);
    end if;
end;
$$;

-- Bucket privado para preservar o PDF original da AE, quando a importação for implementada.
insert into storage.buckets (id, name, public)
values ('documentos-ae', 'documentos-ae', false)
on conflict (id) do nothing;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage' and tablename = 'objects'
          and policyname = 'documentos_ae_authenticated_select'
    ) then
        create policy documentos_ae_authenticated_select
        on storage.objects for select to authenticated
        using (bucket_id = 'documentos-ae');
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage' and tablename = 'objects'
          and policyname = 'documentos_ae_authenticated_insert'
    ) then
        create policy documentos_ae_authenticated_insert
        on storage.objects for insert to authenticated
        with check (bucket_id = 'documentos-ae');
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage' and tablename = 'objects'
          and policyname = 'documentos_ae_authenticated_update'
    ) then
        create policy documentos_ae_authenticated_update
        on storage.objects for update to authenticated
        using (bucket_id = 'documentos-ae')
        with check (bucket_id = 'documentos-ae');
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage' and tablename = 'objects'
          and policyname = 'documentos_ae_authenticated_delete'
    ) then
        create policy documentos_ae_authenticated_delete
        on storage.objects for delete to authenticated
        using (bucket_id = 'documentos-ae');
    end if;
end;
$$;

comment on table public.ae_solicitacoes is
